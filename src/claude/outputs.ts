/**
 * Output schemas the agents must return (validated with zod by runAgent; also sent to the
 * CLI as --json-schema). These are agent-facing shapes; the orchestrator maps them to the
 * persisted schemas in src/schemas (Trend, Idea, ReelSpec, QaCheck, ...).
 */
import { z } from 'zod';
import {
  BeatRole,
  BeatVisual,
  Confidence,
  HookScores,
  IsoDate,
  SfxCue,
  TrendAnalysis,
  wordCount,
} from '../schemas';

export const TrendScoutOutput = z.strictObject({
  analyses: z.array(z.strictObject({ trendId: z.string().min(1), analysis: TrendAnalysis })).max(40),
});
export type TrendScoutOutput = z.infer<typeof TrendScoutOutput>;

export const HookDraft = z.strictObject({
  formulaId: z.string().min(1),
  spoken: z.string().min(1).max(120),
  onScreen: z
    .string()
    .min(1)
    .refine((s) => wordCount(s) <= 7, 'on-screen hook must be 7 words or fewer'),
  scores: HookScores,
  rationale: z.string().max(300).optional(),
});
export type HookDraft = z.infer<typeof HookDraft>;

export const HookMasterOutput = z.strictObject({
  hooks: z.array(HookDraft).length(10, 'exactly 10 hooks are required'),
});
export type HookMasterOutput = z.infer<typeof HookMasterOutput>;

/** Ideas generated by the orchestrator prompt (trend-scout persona is not used for ideas). */
export const IdeaDraft = z.strictObject({
  title: z.string().min(3).max(120),
  premise: z.string().min(10).max(600),
  format: z.string().min(1),
  tags: z.array(z.string().min(1)).max(8),
  trendRefs: z.array(z.string()).max(10),
  scores: z.strictObject({
    trendVelocity: z.number().min(1).max(10),
    nicheFit: z.number().min(1).max(10),
    originality: z.number().min(1).max(10),
    feasibility: z.number().min(1).max(10),
  }),
});
export type IdeaDraft = z.infer<typeof IdeaDraft>;

export const IdeaGenOutput = z.strictObject({ ideas: z.array(IdeaDraft).min(1).max(60) });
export type IdeaGenOutput = z.infer<typeof IdeaGenOutput>;

export const ScriptBeatDraft = z.strictObject({
  role: BeatRole,
  voiceover: z.string().min(1).max(400),
  onScreenText: z.string().refine((s) => wordCount(s) <= 6, 'onScreenText must be 6 words or fewer'),
});

export const FactDraft = z.strictObject({
  claim: z.string().min(1),
  sourceUrl: z.string().nullable(),
  publisher: z.string().nullable(),
  retrievedAt: IsoDate.nullable(),
  supportingQuote: z.string().nullable(),
  status: z.enum(['PENDING', 'HYPOTHETICAL']),
});
export type FactDraft = z.infer<typeof FactDraft>;

export const ScriptWriterOutput = z.strictObject({
  beats: z.array(ScriptBeatDraft).min(5).max(9),
  caption: z.string().min(1).max(1800),
  commentQuestion: z.string().min(3).max(200),
  hashtags: z
    .array(z.string().regex(/^#[\p{L}\p{N}_]+$/u))
    .min(3)
    .max(5),
  facts: z.array(FactDraft).max(20),
});
export type ScriptWriterOutput = z.infer<typeof ScriptWriterOutput>;

export const VisualBeatDraft = z.strictObject({
  sceneType: z.string().min(1),
  visual: BeatVisual,
  motion: z.string().min(1),
  sfx: SfxCue,
});

export const VisualDirectorOutput = z.strictObject({
  beats: z.array(VisualBeatDraft).min(1).max(12),
  coverOffsetMs: z.number().int().min(0).max(5000),
  musicMood: z.string().min(1).max(40),
});
export type VisualDirectorOutput = z.infer<typeof VisualDirectorOutput>;

/**
 * qa-reviewer output = the QA module's VisualReview contract (src/qa/visual.ts), strict here so
 * extra keys are rejected. runVisualQa re-validates it with its own schema (fail closed).
 */
export const QA_ISSUE_KINDS = [
  'hook_unreadable',
  'text_cut_off',
  'garbled_text',
  'deformed_anatomy',
  'logo',
  'real_person',
  'off_brand',
  'other',
] as const;

export const QaReviewerOutput = z.strictObject({
  schemaVersion: z.literal(1),
  hookReadable: z.boolean(),
  textCutOff: z.boolean(),
  garbledText: z.boolean(),
  deformedAnatomy: z.boolean(),
  logosOrRealPeople: z.boolean(),
  onBrand: z.boolean(),
  issues: z
    .array(
      z.strictObject({
        frame: z.number().int().nonnegative().nullable(),
        sceneIndex: z.number().int().nonnegative().nullable(),
        kind: z.enum(QA_ISSUE_KINDS),
        severity: z.enum(['minor', 'major']),
        note: z.string().max(500),
      }),
    )
    .max(50),
  summary: z.string().max(1000),
});
export type QaReviewerOutput = z.infer<typeof QaReviewerOutput>;

/** Originality judge (qa-reviewer persona, no frames): matches JudgeVerdict in src/qa/originality.ts. */
export const OriginalityJudgeOutput = z.strictObject({
  verdict: z.enum(['original', 'copied', 'unsure']),
  reason: z.string().max(1000),
});
export type OriginalityJudgeOutput = z.infer<typeof OriginalityJudgeOutput>;

export const CommunityManagerOutput = z.strictObject({
  replies: z.array(
    z.strictObject({
      commentId: z.string().min(1),
      action: z.enum(['reply', 'skip', 'flag']),
      reply: z.string().max(400).nullable(),
      topicRequest: z.string().max(200).nullable(),
    }),
  ),
});
export type CommunityManagerOutput = z.infer<typeof CommunityManagerOutput>;

export const GrowthAnalystOutput = z.strictObject({
  learnings: z
    .array(z.strictObject({ finding: z.string(), evidence: z.string(), sampleSize: z.number().int().min(0) }))
    .max(5),
  leaderboard: z.array(
    z.strictObject({
      formulaId: z.string(),
      reels: z.number().int().min(0),
      avgWatchTimeSec: z.number().nullable(),
      sharesPer1k: z.number().nullable(),
    }),
  ),
  proposals: z
    .array(
      z.strictObject({
        change: z.string(),
        reason: z.string(),
        sampleSize: z.number().int().min(0),
        confidence: Confidence,
        rollback: z.string(),
      }),
    )
    .max(3),
});
export type GrowthAnalystOutput = z.infer<typeof GrowthAnalystOutput>;
